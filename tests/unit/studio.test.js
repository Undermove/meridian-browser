// Studio's transcript reader and its plain words (src/renderer/dev/studio-transcript.js,
// studio-words.js): no browser needed.
const test = require('node:test');
const assert = require('node:assert/strict');
const ST = require('../../src/renderer/dev/studio-transcript.js');
const W = require('../../src/renderer/dev/studio-words.js');

const ROOT = '/Users/d/Brand';
const line = (o) => JSON.stringify(o);
const user = (uuid, content, extra = {}) => line({ type: 'user', uuid, sessionId: 's1', timestamp: '2026-11-26T10:00:00Z', message: { role: 'user', content }, ...extra });
const asst = (uuid, content) => line({ type: 'assistant', uuid, sessionId: 's1', timestamp: '2026-11-26T10:00:05Z', message: { role: 'assistant', content } });

test('a turn: the prompt, Claude\'s text and its steps in order, each step done when its result comes', () => {
  const m = ST.newModel();
  const text = [
    user('u1', 'Перекрась сайт под бренд'),
    asst('a1', [{ type: 'text', text: 'Сначала посмотрю сайт.' }, { type: 'tool_use', id: 'x1', name: 'mcp__meridian__open_tab', input: { url: 'https://www.zerno.coffee/' } }]),
    asst('a2', [{ type: 'tool_use', id: 'x2', name: 'mcp__meridian__screenshot', input: {} }]),
    user('r1', [{ type: 'tool_result', tool_use_id: 'x1', content: 'ok' }]),
    user('r2', [{ type: 'tool_result', tool_use_id: 'x2', content: [{ type: 'image', source: { type: 'base64', media_type: 'image/png', data: 'AAAA' } }] }]),
  ].join('\n') + '\n';
  assert.equal(ST.feed(m, text, { root: ROOT }), true);
  assert.equal(m.turns.length, 1);
  assert.equal(m.turns[0].prompt, 'Перекрась сайт под бренд');
  assert.deepEqual(m.turns[0].items.map((i) => i.type), ['text', 'steps']);
  const steps = m.turns[0].items[1].steps;
  assert.deepEqual(steps.map((s) => s.state), ['ok', 'ok']);
  assert.equal(m.shots.length, 1);
  assert.match(m.shots[0].src, /^data:image\/png;base64,AAAA$/);
  assert.deepEqual(ST.sitesOf(m), ['https://www.zerno.coffee/']);
});

test('only files the task created or changed inside the folder count; read ones and outside ones don\'t', () => {
  const m = ST.newModel();
  ST.feed(m, [
    user('u1', 'go'),
    asst('a1', [
      { type: 'tool_use', id: 'r', name: 'Read', input: { file_path: `${ROOT}/brief.md` } },
      { type: 'tool_use', id: 'w', name: 'Write', input: { file_path: `${ROOT}/Черновики/palette.png` } },
      { type: 'tool_use', id: 'e', name: 'Edit', input: { file_path: `${ROOT}/Черновики/notes.md` } },
      { type: 'tool_use', id: 'o', name: 'Write', input: { file_path: '/etc/hosts' } },
      { type: 'tool_use', id: 'd', name: 'Edit', input: { file_path: `${ROOT}/../x.md` } },
    ]),
    user('r1', [
      { type: 'tool_result', tool_use_id: 'r', content: 'brief' },
      { type: 'tool_result', tool_use_id: 'w', content: 'ok' },
      { type: 'tool_result', tool_use_id: 'e', content: 'The user doesn\'t want to proceed with this tool use.', is_error: true },
      { type: 'tool_result', tool_use_id: 'o', content: 'ok' },
      { type: 'tool_result', tool_use_id: 'd', content: 'ok' },
    ]),
  ].join('\n') + '\n', { root: ROOT });
  assert.deepEqual([...m.files.keys()], ['Черновики/palette.png']);
  assert.equal(m.files.get('Черновики/palette.png').created, true);
  assert.equal(m.files.get('Черновики/palette.png').image, true);
  const steps = m.turns[0].items[0].steps;
  assert.equal(steps.find((s) => s.id === 'e').state, 'denied');
});

test('commands, hook notes, meta lines, sidechains, broken and repeated lines are not the person\'s words', () => {
  const m = ST.newModel();
  ST.feed(m, [
    user('c1', '<command-name>/clear</command-name>'),
    user('c2', 'Caveat: The messages below were generated by the user while running local commands.'),
    user('c3', 'secret', { isMeta: true }),
    user('c4', 'helper prompt', { isSidechain: true }),
    '{"broken',
    user('u1', 'Сделай отчёт'),
    user('u1', 'Сделай отчёт'),
  ].join('\n') + '\n', { root: ROOT });
  assert.deepEqual(m.turns.map((t) => t.prompt), ['Сделай отчёт']);
});

test('the plan: step i of n and what is being done now', () => {
  const m = ST.newModel();
  ST.feed(m, [user('u1', 'go'), asst('a1', [{ type: 'tool_use', id: 't', name: 'TodoWrite', input: { todos: [
    { content: 'Палитра', activeForm: 'Подбираю палитру', status: 'completed' },
    { content: 'Применить', activeForm: 'Применяю — круг 2', status: 'in_progress' },
    { content: 'Заметки', activeForm: 'Пишу заметки', status: 'pending' },
  ] } }])].join('\n') + '\n', { root: ROOT });
  assert.deepEqual(ST.planProgress(m.plan), { index: 2, total: 3, now: 'Применяю — круг 2', done: 1 });
});

test('steps and questions in plain words, without tool names or jargon', () => {
  const jargon = /\b(MCP|CLI|token|terminal|tool|Bash|git)\b/i;
  for (const lang of ['ru', 'en']) {
    const words = [
      W.stepWords('mcp__meridian__set_boost', {}, lang), W.stepWords('Read', { file_path: '/a/b.md' }, lang),
      W.stepWords('Bash', { command: 'npm test' }, lang), W.stepWords('mcp__figma__get_code', {}, lang),
      W.stepWords('Glob', {}, lang), W.stepWords('SomethingNew', {}, lang),
    ];
    for (const [ic, done, doing] of words) {
      assert.ok(ic && done && doing);
      assert.doesNotMatch(done, jargon);
    }
    for (const tool of ['Edit', 'Write', 'Bash', 'mcp__meridian__set_boost', 'mcp__figma__x', 'WebFetch', 'Other']) {
      const [title] = W.askWords(tool, '/Users/d/Brand/colors.css', lang);
      assert.match(title, /\?$/);
      assert.doesNotMatch(title, jargon);
    }
  }
  assert.equal(W.askWords('Edit', '/Users/d/Brand/colors.css', 'ru')[0], 'Разрешить менять файлы в папке Brand?');
  assert.equal(W.stepWords('Bash', { description: 'Run the checks' }, 'en')[1], 'Run the checks');
  assert.equal(W.stepWords('mcp__meridian__navigate', { url: 'https://www.zerno.coffee/x' }, 'ru')[1], 'Открыл сайт zerno.coffee');
});

test('every word exists in both languages', () => {
  const ru = Object.keys(W.T.ru).sort(), en = Object.keys(W.T.en).sort();
  assert.deepEqual(ru, en);
});
