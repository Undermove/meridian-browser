#!/usr/bin/env python3
"""Writes the WebUI icons.ts from the Electron build's src/renderer/icons.js.

  chromium/tools/gen_icons.py <icons.js> <icons.ts> name [name ...]

Each icon becomes a whole <svg> in one Lit template (Lit parses SVG children
only inside an <svg> of the same template).
"""
import re
import sys

HEADER = '''// Copyright 2026 The Meridian Authors
// Use of this source code is governed by a BSD-style license that can be
// found in the LICENSE file.

// Meridian icons (from the Electron build's src/renderer/icons.js): 24x24,
// 2px round strokes in currentColor. Each is a whole <svg> in one template,
// because Lit only parses SVG children inside an <svg> of the same template.
// Generated by chromium/tools/gen_icons.py; to add one, rerun it with the name.

import {html} from '//resources/lit/v3_0/lit.rollup.js';
import type {TemplateResult} from '//resources/lit/v3_0/lit.rollup.js';
'''


# Icons the Electron build defines elsewhere (Mission Control's own) or doesn't
# have (the sidebar's mini player).
EXTRA = {
    'pause': '<rect x="7" y="5.5" width="3.2" height="13" rx="1" fill="currentColor" stroke="none"/><rect x="13.8" y="5.5" width="3.2" height="13" rx="1" fill="currentColor" stroke="none"/>',
    'playFilled': '<path d="M8 5.5l10.5 6.5L8 18.5z" fill="currentColor" stroke-linejoin="round"/>',
    'next': '<path d="M5.5 6l8 6-8 6z" fill="currentColor" stroke-linejoin="round"/><path d="M18 6v12"/>',
    'previous': '<path d="M18.5 6l-8 6 8 6z" fill="currentColor" stroke-linejoin="round"/><path d="M6 6v12"/>',
    'pip': '<rect x="3.5" y="5" width="17" height="14" rx="2"/><rect x="11.5" y="11.5" width="6.5" height="5" rx="1" fill="currentColor" stroke="none"/>',
    'agents': '<circle cx="12" cy="12" r="2.2"/><path d="M12 4.5a7.5 7.5 0 0 1 7.5 7.5"/><path d="M4.5 12A7.5 7.5 0 0 1 12 4.5" opacity=".55"/><path d="M19.5 12A7.5 7.5 0 0 1 12 19.5"/><path d="M12 19.5A7.5 7.5 0 0 1 4.5 12" opacity=".55"/><circle cx="19.5" cy="12" r="1.3" fill="currentColor" stroke="none"/><circle cx="4.5" cy="12" r="1.3" fill="currentColor" stroke="none"/>',
}


def main():
  src, out, names = sys.argv[1], sys.argv[2], sys.argv[3:]
  js = open(src, encoding='utf-8').read()
  paths = dict(re.findall(r"^  (\w+): '(.*)',$", js, re.M))
  paths.update(EXTRA)
  missing = [n for n in names if n not in paths]
  if missing:
    sys.exit('not in icons.js: ' + ', '.join(missing))
  lines = [HEADER, 'export type IconName =']
  lines += [f"    '{n}'{'|' if i < len(names) - 1 else ';'}"
            for i, n in enumerate(names)]
  lines += ['', 'export function icon(name: IconName, size = 16): TemplateResult {',
            '  switch (name) {']
  for n in names:
    lines.append(f"    case '{n}':")
    lines.append(
        '      return html`<svg width="${size}" height="${size}" '
        'viewBox="0 0 24 24" fill="none" stroke="currentColor" '
        'stroke-width="2" stroke-linecap="round" stroke-linejoin="round" '
        f'aria-hidden="true">{paths[n]}</svg>`;')
  lines += ['  }', '}', '']
  open(out, 'w', encoding='utf-8').write('\n'.join(lines))


if __name__ == '__main__':
  main()
